"""
위기 신호(자해/자살) 감지 — RAG·LLM 의존성과 분리된 경량 안전 모듈.

무거운 임베딩 모델이나 네트워크 없이 단독으로 import·테스트·평가할 수 있도록
순수 함수로 제공한다. (backend/eval/evaluate_crisis.py 가 이 모듈을 직접 사용한다.)
"""
import re

# 자해/자살 위기 신호 키워드 (공백 제거 후 매칭). 안전을 위해 재현율(Recall)을 우선한다.
CRISIS_KEYWORDS = [
    "자살", "자해",
    "죽고싶", "죽어버리", "죽어야겠", "죽는게나아", "죽는편이",
    "목숨을끊", "목숨끊", "목숨을버리",
    "생을마감", "생을포기", "삶을포기", "삶을마감",
    "세상을떠나", "세상에서사라지", "세상에서없어지",
    "사라지고싶", "없어지고싶", "사라져버리고싶",
    "살고싶지않", "살기싫", "살아갈이유가없", "살이유가없", "살아갈힘이없", "살아갈자신이없",
    "다끝내고싶", "끝내버리고싶", "다끝내버리",
    "뛰어내리", "목을매", "목매달", "손목을긋", "손목긋", "약을먹고죽", "수면제를먹고",
]


def detect_crisis(text: str) -> bool:
    """
    사용자 입력에서 자해/자살 등 위기 신호를 감지한다.

    공백을 제거해 '죽 고 싶다'처럼 띄어쓰기로 회피하는 표현까지 포착하며,
    안전을 위해 정밀도(Precision)보다 재현율(Recall)을 우선하는 키워드 필터다.
    """
    if not text:
        return False
    normalized = re.sub(r"\s+", "", text)
    return any(kw in normalized for kw in CRISIS_KEYWORDS)
